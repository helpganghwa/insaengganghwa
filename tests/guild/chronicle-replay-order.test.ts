import { describe, expect, it } from 'vitest';

import { replayOrderIssues } from '@/lib/game/guild/conquest/chronicle';

/** 연출 순서 검증(2026-09-05) — 회고 문장(어제·하루 만에)에만 마커로 등장하는 전투 구역을 잡는다. */
const ZONES = ['흑요석 보루', '재의 길목', '용암 하구', '용의 해골', '불탄 마을', '그을린 고목', '전사의 막사'];

describe('replayOrderIssues', () => {
  it('9/5 발행분 — 회고 문장에만 등장한 세 구역을 잡는다', () => {
    const text =
      '드래곤 화산에서는 어제 {g|왕실|25}이 {g|케프리|33}에게 내주었던 {z|흑요석 보루|4}를 두고 다시 다툼이 벌어졌다. {g|케프리|33}는 이번에도 방어 병력을 세우지 못했고, {g|왕실|25}은 하루 만에 {z|흑요석 보루|4}를 되찾았다. 같은 지역의 {z|재의 길목|6} 역시 비어 있었다.\n\n' +
      '어제 얻은 {z|용암 하구|9}를 지키러 나선 수비수 한 명은 {g|티모집사|31}의 공세를 막아내지 못했고, 결국 {z|용암 하구|9}는 하루 만에 {g|티모집사|31}의 손에 넘어갔다. {g|게이들|32}은 {z|용의 해골|5}을 거두어들였다.\n\n' +
      '{g|민초|28}의 공세를 받은 {z|불탄 마을|7}은 어제 손에 넣은 땅을 하루 만에 지켜낸 것이었고, {g|케케케|27}가 노린 {z|그을린 고목|8}에서는 {u|벼락게이|HuNn1UgB}가 자리를 지켰다. {g|QWER|34}이 노린 {z|전사의 막사|32}는 {g|Winners|17}가 막아섰다.';
    expect(replayOrderIssues(text, ZONES)).toEqual(['용암 하구', '불탄 마을', '그을린 고목']);
  });

  it('행동 문장에 먼저 두고 회고는 대명사로 받으면 위반 없음', () => {
    const text =
      '{g|왕실|25}이 {z|흑요석 보루|4}를 다시 노렸다. 어제 {g|케프리|33}에게 내주었던 땅이다. {g|왕실|25}은 하루 만에 그곳을 되찾았다.\n\n' +
      '{g|티모집사|31}는 {z|용암 하구|9}로 밀려들었다. 어제 {g|왕실|25}이 얻은 땅이었지만 수비수 한 명은 버티지 못했고, 그곳은 하루 만에 {g|티모집사|31}의 손에 넘어갔다.\n\n' +
      '{g|민초|28}는 {z|불탄 마을|7}을, {g|케케케|27}는 {z|그을린 고목|8}을 노렸다. 두 곳 모두 어제 {g|게이들|32}이 손에 넣은 땅이었는데, {u|벼락게이|HuNn1UgB}가 자리를 지켰다.';
    expect(replayOrderIssues(text, ZONES)).toEqual([]);
  });

  it('본문에 아예 안 나온 구역은 문제로 잡지 않는다(종료 일괄 발화 대상)', () => {
    expect(replayOrderIssues('{g|왕실|25}이 {z|재의 길목|6}을 거두었다.', ZONES)).toEqual([]);
  });
});
