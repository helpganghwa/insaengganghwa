-- 유령 테이블 runes 제거 (2026-08-12 컷오버 분류 감사)
--
-- 스테이징에만 존재하고 프로덕션엔 없던 0행 테이블. 마이그레이션·수동 SQL 어디에도 생성문이
-- 없어(손으로 만든 뒤 방치) 스키마 재구성으로도 되살아나지 않고, 코드 참조도 없다.
-- 컬럼(user_id·server_id·attrs·source_profile_id·name)으로 보아 도입되지 않은 룬 시스템의 흔적.
--
-- 지우는 이유는 정리 자체보다 **가드를 살려 두기 위해서**다. cutover-live.ts가 "public 테이블은
-- 전부 삭제·보존으로 분류돼 있어야 한다"를 검사하는데, 이 테이블이 남아 있으면 스테이징
-- 드라이런이 상시 실패한다. 늘 실패하는 가드는 곧 무시된다.
--
-- 목록(WIPE_TABLES)에 넣는 선택은 하지 않았다 — 프로덕션엔 없는 이름이라 그쪽 실행에서
-- "목록에만 있고 DB엔 없음" 가드에 걸린다.
--
-- 참조하는 FK 없음·0행 확인 후 적용(프로덕션은 애초에 대상 없음 — if exists로 무해).

drop table if exists public.runes;
