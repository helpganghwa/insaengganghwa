-- 0205 (2026-09-20) 세금 수금 권한 분리 소급 — 종전 '세금 수금 · 분배'(taxDistribute, 비트 128)를 받았던 부길드장에게
-- 새 '세금 수금'(taxCollect, 비트 512)을 함께 켜 준다. 배포 직후에도 하던 수금을 그대로 할 수 있게(사용자 확정).
-- 길드장은 항상 전권이라 대상이 아니다. 권한은 멤버 행 단위라 서버 구분 없이 전 서버에 적용한다.
--
-- ⚠ **새 코드가 실서버에 올라간 직후 딱 한 번만** 돌린다. 그 뒤에는 다시 돌리지 않는다.
--   이 문은 '분배 ON · 수금 OFF'인 부길드장을 전부 찾는데, 배포 뒤에는 그 상태가 길드장이 **일부러** 만든 설정일 수 있다
--   (수금과 분배를 다른 사람에게 맡기는 것이 이 기능의 목적이다). 늦게 돌리거나 재적용하면 그 설정을 조용히 되돌린다.
--   배포 전에 미리 돌리지도 않는다 — 옛 코드의 권한 저장은 모르는 비트(512)를 지워 버려 두 번째 실행이 필요해진다.
--   배포와 실행 사이 몇 분은 종전 분배 부길드장의 대리 수금이 막히지만(집행관 본인·길드장은 정상) 금전 손실은 없다.
--
-- 실행 전 대상 수 확인:
--   select count(*) from guild_members where role = 'vice' and (permissions & 128) <> 0 and (permissions & 512) = 0;
-- 다음 날 점검(0건이 아니면 set_perm 기록의 before/after와 대조해 길드장이 끈 것인지 본다):
--   같은 select.
update guild_members
   set permissions = permissions | 512
 where role = 'vice'
   and (permissions & 128) <> 0
   and (permissions & 512) = 0;
